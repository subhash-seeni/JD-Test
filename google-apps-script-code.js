/**
 * Google Apps Script Webhook for Assessment Test Results
 * 
 * 1-MINUTE SETUP INSTRUCTIONS:
 * 1. Open https://script.google.com while logged into your subhash@geotrixteam.com account.
 * 2. Click "New project" (name it "Assessment Results Mailer").
 * 3. Replace all the code in Code.gs with this entire script.
 * 4. Click "Deploy" > "New deployment".
 * 5. Click the gear icon next to "Select type" and choose "Web app".
 * 6. Set:
 *    - Description: "Assessment Results"
 *    - Execute as: "Me (subhash@geotrixteam.com)"
 *    - Who has access: "Anyone" (allows the test app to send results)
 * 7. Click "Deploy" and authorize permissions if prompted.
 * 8. Copy the generated "Web App URL" (starts with https://script.google.com/macros/s/...)
 *    and paste it into src/emailConfig.js as GOOGLE_APPS_SCRIPT_URL.
 */

function doPost(e) {
  try {
    var data = JSON.parse(e.postData.contents);
    
    var recipient = data.to_email || "subhash@geotrixteam.com";
    var candidateName = data.candidate_name || "Unknown Candidate";
    var candidateEmail = data.candidate_email || "Not provided";
    var totalScore = data.total_score || "N/A";
    var mcqBreakdown = data.mcq_breakdown || "N/A";
    var topicBreakdown = data.topic_breakdown || "";
    var codeBreakdown = data.code_breakdown || "";
    var timeTaken = data.time_taken || "N/A";
    var timestamp = data.submission_timestamp || new Date().toLocaleString();

    var subject = "Assessment Result: " + candidateName + " - Score: " + totalScore;

    // Plain text version
    var plainBody = "JUNIOR DEVELOPER ASSESSMENT TEST RESULTS\n" +
      "==================================================\n\n" +
      "Candidate Name: " + candidateName + "\n" +
      "Candidate Email: " + candidateEmail + "\n" +
      "Submitted At: " + timestamp + "\n" +
      "Time Taken: " + timeTaken + "\n\n" +
      "OVERALL SCORE: " + totalScore + "\n" +
      "MCQ Accuracy: " + mcqBreakdown + "\n\n" +
      "PERFORMANCE BY TOPIC:\n" +
      topicBreakdown + "\n\n" +
      "CODE IMPLEMENTATION BREAKDOWN & SUBMITTED CODE:\n" +
      codeBreakdown + "\n\n" +
      "---\nAuto-generated by Junior Developer Skills Assessment App";

    // Clean HTML version for inbox readability
    var htmlBody = '<div style="font-family: Arial, sans-serif; max-width: 680px; margin: 0 auto; color: #1e293b; line-height: 1.5;">' +
      '<div style="background: #0f172a; padding: 20px 24px; border-radius: 6px 6px 0 0; color: #ffffff;">' +
      '<h2 style="margin: 0; font-size: 20px;">Junior Developer Assessment Results</h2>' +
      '<p style="margin: 4px 0 0; font-size: 13px; color: #94a3b8;">Automated evaluation report for ' + candidateName + '</p>' +
      '</div>' +
      '<div style="background: #ffffff; border: 1px solid #e2e8f0; border-top: none; padding: 24px; border-radius: 0 0 6px 6px;">' +
      '<div style="background: #f8fafc; border: 1px solid #e2e8f0; border-radius: 6px; padding: 16px; margin-bottom: 20px;">' +
      '<table style="width: 100%; font-size: 14px; border-collapse: collapse;">' +
      '<tr><td style="padding: 4px 0; color: #64748b; width: 140px;">Candidate:</td><td style="font-weight: bold;">' + candidateName + '</td></tr>' +
      '<tr><td style="padding: 4px 0; color: #64748b;">Email:</td><td><a href="mailto:' + candidateEmail + '">' + candidateEmail + '</a></td></tr>' +
      '<tr><td style="padding: 4px 0; color: #64748b;">Time Taken:</td><td>' + timeTaken + '</td></tr>' +
      '<tr><td style="padding: 4px 0; color: #64748b;">Submission Time:</td><td>' + timestamp + '</td></tr>' +
      '<tr style="border-top: 1px solid #e2e8f0;"><td style="padding: 10px 0 4px; color: #0f172a; font-weight: bold; font-size: 16px;">Overall Score:</td><td style="padding: 10px 0 4px; font-weight: bold; font-size: 18px; color: #2563eb;">' + totalScore + '</td></tr>' +
      '<tr><td style="padding: 4px 0; color: #64748b;">MCQ Performance:</td><td>' + mcqBreakdown + '</td></tr>' +
      '</table>' +
      '</div>' +
      '<h3 style="font-size: 15px; margin: 20px 0 8px; color: #0f172a; border-bottom: 2px solid #e2e8f0; padding-bottom: 6px;">Topic Breakdown</h3>' +
      '<pre style="background: #f1f5f9; padding: 12px; border-radius: 4px; font-size: 13px; font-family: monospace; white-space: pre-wrap;">' + topicBreakdown + '</pre>' +
      '<h3 style="font-size: 15px; margin: 24px 0 8px; color: #0f172a; border-bottom: 2px solid #e2e8f0; padding-bottom: 6px;">Code Questions & Submitted Solutions</h3>' +
      '<pre style="background: #0f172a; color: #f8fafc; padding: 14px; border-radius: 4px; font-size: 12.5px; font-family: monospace; white-space: pre-wrap; overflow-x: auto;">' + codeBreakdown + '</pre>' +
      '<p style="font-size: 11.5px; color: #94a3b8; margin-top: 24px;">Note: Code question scores are auto-graded and approximate — please spot-check before final evaluation.</p>' +
      '</div>' +
      '</div>';

    MailApp.sendEmail({
      to: recipient,
      subject: subject,
      body: plainBody,
      htmlBody: htmlBody
    });

    return ContentService.createTextOutput(JSON.stringify({ status: "success" }))
      .setMimeType(ContentService.MimeType.JSON);
  } catch (error) {
    return ContentService.createTextOutput(JSON.stringify({ status: "error", message: error.toString() }))
      .setMimeType(ContentService.MimeType.JSON);
  }
}
